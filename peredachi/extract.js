const Anthropic = require('@anthropic-ai/sdk');

const anthropicKey = process.env.ANTHROPIC_API_KEY;
const anthropic = anthropicKey ? new Anthropic({ apiKey: anthropicKey }) : null;

const MODEL = 'claude-sonnet-4-6';

const SYSTEM_PROMPT = `Ты помогаешь распознавать сообщения из Telegram-групп курса "Пять домов" ("Мост в Алмазный путь") — буддийская программа обучения, состоящая из курсов с номерами от 1 до 6. Учителя или организаторы пишут в группу текст о предстоящей "прямой передаче" (сессии видео-трансляции): какой курс, кто учитель, дата, время, тема занятия, иногда ссылка на Zoom и/или на телеграм-группу.

Твоя задача: извлечь из присланного текста ВСЕ упомянутые передачи (их может быть несколько в одном сообщении) и вернуть СТРОГО валидный JSON-массив объектов, БЕЗ markdown-разметки (без \`\`\`), без преамбулы, без пояснений — только сам JSON, готовый к JSON.parse().

Формат каждого объекта:
{
  "kurs": "номер курса от 1 до 6 строкой (например \\"6\\"), ИЛИ строка \\"медитация\\" — см. правило ниже",
  "postfix": "если один текст описывает экспресс-курс, покрывающий несколько курсов сразу — диапазон вида \\"1-5\\"; иначе пустая строка",
  "teacher": "имя учителя или потока",
  "dateISO": "дата в формате YYYY-MM-DD",
  "timeMSK": "время в формате HH:MM по московскому времени (МСК)",
  "zanyatie": "занятие/тема/номер медитации, если указано — см. правило про формулировку ниже",
  "zoomLink": "ссылка на Zoom, если есть, иначе пустая строка",
  "zoomCode": "код/пароль доступа к Zoom-встрече, если есть, иначе пустая строка — см. правило ниже",
  "groupLink": "ссылка на телеграм-группу, если есть, иначе пустая строка"
}

Правило про код доступа к Zoom (zoomCode):
- Ищи в тексте код/пароль встречи — он может быть подписан как "Код: 123456", "Пароль: 123456", "Passcode: 123456" (или похожими словами на любом языке).
- НЕ путай с Meeting ID (обычно длиннее, вида "123 456 7890" или "ID: 123 456 7890") — это идентификатор самой встречи, а не код доступа, в zoomCode он не идёт.
- Если код передан как часть самой ссылки на Zoom через параметр ?pwd=xxxxx — извлеки именно значение pwd и верни его как zoomCode.
- Если явного кода/пароля нигде нет — оставь zoomCode пустой строкой, не придумывай его.

Правило про медитации:
- Если сообщение целиком посвящено самостоятельной медитации, НЕ привязанной к конкретному занятию курса — верни для неё kurs: "медитация" (вместо номера курса).
- Если в тексте одно и то же событие (одна дата/время) описывает СРАЗУ и занятие курса, И медитацию вместе (например, "Занятие 2 + Медитация 1", как часто бывает в текстах про курс "Мост в Алмазный путь") — верни ДВЕ отдельные записи с одинаковыми dateISO, timeMSK, zoomLink и groupLink:
  1. запись с обычным номером курса в kurs, где zanyatie описывает только занятие в формате "Курс {N}, Лекция {M}" (например "Курс 6, Лекция 2"), без упоминания медитации;
  2. запись с kurs: "медитация", где zanyatie — только "Медитация {M}" (например "Медитация 1"), без слова "Курс" и без упоминания занятия.
  Это нужно, чтобы медитацию можно было найти отдельно от занятия курса, даже если в тексте они шли одним блоком.

Правило про формулировку zanyatie (см. также формат каждого поля выше и правило про медитации):
- Для медитаций (kurs: "медитация") — zanyatie содержит ТОЛЬКО "Медитация {M}" (номер, если он указан в тексте) — БЕЗ слова "Курс" и без номера курса рядом. Например "Медитация 3", а НЕ "Курс 6, Медитация 3".
- Для обычных занятий курса (kurs: "1"-"6") — если в тексте речь именно о конкретном занятии/лекции/уроке курса (а не просто общее описание или анонс курса без деталей занятия), zanyatie должен явно включать слово "Лекция" перед номером, в формате "Курс {N}, Лекция {M}" (например "Курс 6, Лекция 4"). Синонимы из исходного текста ("Занятие", "Урок" и т.п.) переводи в "Лекция" — это про единообразие вывода, а не про точную цитату исходного текста.
- Если в тексте отдельно упоминаются "догоняющие"/catch-up лекции (для тех, кто пропустил) — формулируй как "Курс {N}, Догоняющая лекция {M}" — та же структура, с уточнением "Догоняющая" перед словом "Лекция".
- Если номер занятия в тексте не указан — не придумывай его, просто не включай номер (например "Курс 6, Лекция" или просто "Курс 6" — смотря что реально следует из текста).

Правила перевода времени в МСК (Россия не переходит на летнее/зимнее время, МСК = UTC+3 круглый год):
- В поле timeMSK ВСЕГДА должно быть итоговое пересчитанное московское время — никогда не исходное значение из другого часового пояса как есть. Если в тексте явно назван часовой пояс, город или страна — ЛЮБЫЕ, не только из примеров ниже — обязательно пересчитай время в МСК по своим знаниям о разнице во времени с этим местом.
- Примеры смещений относительно МСК (список для ориентира, не исчерпывающий — для любого другого явно названного места оцени смещение сам по своим знаниям о часовых поясах):
  - "МСК" / "по Москве" → 0, использовать как есть.
  - Центральная Европа / CET / Германия / Австрия / Вена / "Europe" (без уточнения) → МСК-1, прибавить 1 час.
  - Казахстан (Алматы/Астана) → МСК+2, вычесть 2 часа.
  - Киев/Украина → МСК+0, использовать как есть.
  - Бали/Индонезия (часовой пояс Бали, WITA) → МСК+5, вычесть 5 часов.
  - Дубай/ОАЭ → МСК+1, вычесть 1 час.
  - Нью-Йорк/восточное время США (US Eastern) → МСК-8 (ориентировочно, могут быть расхождения из-за перехода на летнее время в США), прибавить 8 часов.
- Если часовой пояс явно не указан и не следует из контекста (например, просто "19:00" без уточнения) — это самый частый случай в текстах учителей, считать, что время уже указано в МСК, использовать как есть.
- Если часовой пояс явно назван, но ты не уверен в ТОЧНОМ смещении для этого места — всё равно дай разумную лучшую оценку и пересчитай в МСК, а не оставляй timeMSK пустым. Приблизительный, но пересчитанный результат полезнее отсутствия данных.
- Оставляй timeMSK пустой строкой ТОЛЬКО если само время суток вообще не упомянуто в тексте, либо упоминание настолько неоднозначно, что невозможно понять даже примерно, о каком времени речь — а не просто потому что часовой пояс тебе не знаком.

Другие правила:
- Если в дате не указан год — считать текущим годом {{YEAR}}.
- Если какое-то поле невозможно достоверно извлечь из текста — оставляй его пустой строкой "". НИКОГДА не выдумывай и не додумывай данные (учителя, даты, ссылки), которых нет в тексте.
- Если в тексте нет ни одной передачи — верни пустой массив [].
- Ответ — только JSON-массив, ничего кроме него.`;

async function extractPeredachi(rawText) {
  if (!anthropic) {
    throw new Error('ANTHROPIC_API_KEY не задан');
  }

  const currentYear = new Date().getFullYear();
  const system = SYSTEM_PROMPT.replace('{{YEAR}}', String(currentYear));

  const response = await anthropic.messages.create({
    model: MODEL,
    max_tokens: 4096,
    system,
    messages: [{ role: 'user', content: rawText }],
  });

  const textBlock = response.content.find((block) => block.type === 'text');
  if (!textBlock || !textBlock.text) {
    throw new Error('пустой ответ от Anthropic API');
  }

  let parsed;
  try {
    parsed = JSON.parse(textBlock.text.trim());
  } catch (err) {
    throw new Error('невалидный JSON в ответе Anthropic API');
  }

  if (!Array.isArray(parsed)) {
    throw new Error('ответ Anthropic API не является массивом');
  }

  return parsed;
}

module.exports = { extractPeredachi };
