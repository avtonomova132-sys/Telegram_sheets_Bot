// Пассивный мониторинг Telegram-групп на анонсы передач (см. index.js,
// обработчик bot.on('message', ...) для групп из WATCHED_GROUP_IDS).

// WATCHED_GROUP_IDS — chat_id групп через запятую, которые Elena добавляет
// вручную через переменную окружения на Railway. Пустой список по
// умолчанию — мониторинг не активен, пока она сама не подключит группу.
function getWatchedGroupIds() {
  return new Set(
    String(process.env.WATCHED_GROUP_IDS || '')
      .split(',')
      .map((id) => id.trim())
      .filter(Boolean)
  );
}

// Упоминание курса/программы: "курс"/"передача" рядом с цифрой 1-6 (в любом
// порядке), название программы целиком, или медитация (тоже полноценная
// запись в системе — kurs: "медитация").
const COURSE_RE =
  /пять\s*домов|мост\s*(?:в|к)?\s*алмазн|медитац|курс\w*\D{0,5}[1-6]\b|\b[1-6]\D{0,5}курс|передач\w*\D{0,5}[1-6]\b|\b[1-6]\D{0,5}передач/i;

// Дата: число+месяц текстом ("21 августа", "21-го августа", "5го сентября",
// "21, августа" — между числом и месяцем допускаем необязательные дефис,
// окончание "го"/"ого" и/или запятую в любом сочетании) или цифрами
// ("21.08", "21/08"), день недели ("четверг"), либо относительная
// ("сегодня"/"завтра") — точное число не обязательно, extractPeredachi
// разберётся с абсолютной датой сам.
const NUMERIC_DATE_RE =
  /\b\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?\b|\b\d{1,2}\s*-?\s*(?:ого|его|го)?\s*,?\s*(?:январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр)/i;
const WEEKDAY_RE = /понедельник|вторник|сред[ауы]|четверг|пятниц\w*|суббот\w*|воскресень\w*/i;
const RELATIVE_DAY_RE = /завтра|сегодня/i;

// Время в любом формате: "19:00"/"17-00" (двоеточие, точка или дефис),
// "в 7 вечера"/"11 утра" (час словом части суток), "11 по Бали"/"19 по
// Москве" (час + "по <пояс>", без требования конкретного названия пояса).
const HHMM_RE = /\b\d{1,2}[:.\-]\d{2}\b/;
const MERIDIEM_RE = /\d{1,2}\s*(?:час\w*\s*)?(?:утра|вечера|дня|ночи)/i;
const TZ_HOUR_RE = /\b\d{1,2}\s+по\s+\S+/i;

function hasCourseMention(text) {
  return COURSE_RE.test(text);
}

function hasDateMention(text) {
  return NUMERIC_DATE_RE.test(text) || WEEKDAY_RE.test(text) || RELATIVE_DAY_RE.test(text);
}

function hasTimeMention(text) {
  return HHMM_RE.test(text) || MERIDIEM_RE.test(text) || TZ_HOUR_RE.test(text);
}

// Дешёвая эвристика без вызова Anthropic API — только чтобы отсеять
// заведомо нерелевантные сообщения (болтовню, стикеры, вопросы без даты) и
// не тратить API-вызов на каждое сообщение в группе. Не пытается быть
// точной: ложные срабатывания — это нормально, извлечение (extractPeredachi)
// разберётся точнее; ложные пропуски — то, чего эвристика должна избегать,
// поэтому требуются все три признака сразу (курс/программа + дата + время),
// но каждый — в широком наборе форматов, а не только "привычном".
function looksLikeAnnouncement(text) {
  if (!text) return false;
  return hasCourseMention(text) && hasDateMention(text) && hasTimeMention(text);
}

module.exports = { getWatchedGroupIds, looksLikeAnnouncement };
